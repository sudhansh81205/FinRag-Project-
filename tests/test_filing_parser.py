def test_real_source_identity_counts_and_record_contract(raw, manifest, parsed):
    narrative, tables, summary = parsed
    assert sha256(raw) == manifest["raw_sha256"]
    assert summary["narrative_by_section"] == {"Item 1A": 128, "Item 7": 50, "Item 8": 138}
    assert summary["total_records"] == 319
    assert len(tables) == 3
    assert len({r["id"] for r in narrative + tables}) == 319
    for record in narrative + tables:
        assert record["id"].startswith(ACCESSION + ":")
        assert record["metadata"]["source_sha256"] == manifest["raw_sha256"]
        assert record["metadata"]["content_sha256"] == sha256(record["content"].encode("utf-8"))
        assert all(isinstance(v, (str, int, float, bool)) for v in record["metadata"].values())


def test_every_narrative_record_resolves_to_its_exact_source_substring(raw, parsed):
    soup = BeautifulSoup(raw.decode("utf-8"), "lxml")
    source_text = {}
    for record in parsed[0]:
        meta = record["metadata"]
        key = meta["source_locator"]
        if key not in source_text:
            matches = soup.select(key)
            assert len(matches) == 1
            assert matches[0].find_parent("table") is None
            source_text[key] = clean_text(matches[0])
        assert record["content"] == source_text[key][meta["char_start"]:meta["char_end"]]
        assert 0 < len(record["content"]) <= 1000
        assert "TABLE OF CONTENTS" not in record["content"]
    risk = " ".join(r["content"] for r in parsed[0] if r["metadata"]["section"] == "Item 1A")
    assert "Risks Related to COVID-19" not in risk  # Short heading is not standalone evidence.
    assert "pandemic" in risk
    assert "Unresolved Staff Comments" not in risk


