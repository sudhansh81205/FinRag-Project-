@pytest.mark.parametrize(("old", "new", "message"), [
    ('id="item1A"', 'id="missing"', "Invalid body anchor"),
    ('href="#item1B"', 'href="#missing"', "Invalid body anchor"),
    ('Item 1A. Section title', 'Item 1. Wrong section', "Body heading"),
    ('CONSOLIDATED BALANCE SHEETS', 'UNSUPPORTED TABLE', "statement heading"),
    ('(In millions)', '(No declared scale)', "declared units"),
    ('<td>(12)</td>', '<td rowspan="2">(12)</td>', "table span"),
    ('2021</ix:nonnumeric>', '2022</ix:nonnumeric>', "identity check"),
])
def test_invalid_inputs_fail_instead_of_silent_partial_success(small_source, old, new, message):
    text, manifest = small_source
    with pytest.raises(ParseError, match=message):
        parse_filing(text.replace(old, new).encode(), manifest)


def test_hidden_content_never_becomes_narrative(small_source):
    text, manifest = small_source
    text = text.replace('meaningful narrative', 'meaningful <span hidden>HIDDEN_SENTINEL</span> narrative')
    narratives, _, _ = parse_filing(text.encode(), manifest)
    assert all("HIDDEN_SENTINEL" not in r["content"] for r in narratives)


@pytest.mark.parametrize("text", ["word " * 600, "z" * 2401, "short"])
def test_chunking_covers_every_character_without_discarding_final_tail(text):
    covered = set()
    for start, end, chunk in slices(text):
        assert chunk == text[start:end]
        assert len(chunk) <= 1000
        covered.update(range(start, end))
    assert covered == set(range(len(text)))


def test_bad_source_checksum_and_wrong_accession_are_rejected(raw, manifest):
    with pytest.raises(ParseError, match="checksum"):
        validate_source(raw + b" ", manifest)
    with pytest.raises(ParseError, match="Only the declared"):
        validate_source(raw, {**manifest, "accession": "different-filing"})
    with pytest.raises(ParseError, match="Only the declared"):
        validate_source(raw, {**manifest, "company": "Different company"})
    with pytest.raises(ParseError, match="Manifest scope"):
        validate_source(raw, {**manifest, "selected_sections": ["Item 9"]})


def test_failed_run_preserves_existing_output_and_manifest(tmp_path, manifest):
    source = tmp_path / "bad.htm"
    source.write_bytes(b"not a filing")
    m = tmp_path / "manifest.json"
    m.write_text(json.dumps({**manifest, "raw_path": str(source)}), encoding="utf-8")
    before = m.read_bytes()
    output = tmp_path / "output"
    output.mkdir()
    (output / "narrative.jsonl").write_text("previous valid output", encoding="utf-8")
    with pytest.raises(ParseError, match="checksum"):
        run(m, output)
    assert m.read_bytes() == before
    assert (output / "narrative.jsonl").read_text() == "previous valid output"


def test_clean_restore_from_archive_and_second_run_match(tmp_path, manifest):
    raw_path = tmp_path / "raw" / "filing.html"
    manifest_path = tmp_path / "manifest.json"
    manifest_path.write_text(json.dumps({**manifest, "raw_path": str(raw_path)}), encoding="utf-8")
    output = tmp_path / "parsed"
    first = run(manifest_path, output)
    assert sha256(raw_path.read_bytes()) == manifest["raw_sha256"]
    before = {p.name: p.read_bytes() for p in output.iterdir()}
    assert run(manifest_path, output) == first
    assert {p.name: p.read_bytes() for p in output.iterdir()} == before
    assert json.loads(manifest_path.read_text())["state"] == "parsed_not_indexed"
